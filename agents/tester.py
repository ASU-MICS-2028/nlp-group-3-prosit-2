"""Tester agent: black-box tests from the spec, run in the sandbox, failures explained for the coder.

Two layers:
1. tests/test_contract.py, generated by code (no LLM): auth 401/403, unknown ids 404, invalid bodies 422.
2. tests/test_behaviour.py, written by the LLM in a ReAct loop: happy paths and every business rule.

The tester sees the spec only, never the code, so its tests check the spec rather than the coder's
reading of it. It triages each failure: a test that misreads the spec gets fixed, an app that breaks
the spec gets reported. The report goes to state.test_report and sends the coder back in.
"""
import json
import pathlib
import re
import time
from typing import Callable, Optional

from core.llm import LLM, extract_json
from core.sandbox import run_checks
from core.spec import Spec
from core.state import LogEntry, ProjectState
from core.tools import Tool, describe

MAX_STEPS = 12
MAX_FILE = 60_000
MAX_OBS = 6000
CONTRACT_FILE = "tests/test_contract.py"

SYSTEM = """You are the tester agent. You write black-box pytest tests for a FastAPI app from its API spec.
You cannot see the app's code. Test what the spec promises, nothing else.

You work in steps. Each reply is ONE JSON object and nothing else:
{{"thought": "<one line: what this step does>", "action": "<tool name or finish>", "args": {{...}}}}

Tools:
{tools}
- finish: you are done. Only allowed after run_tests with no test changes since.
  All tests passed: args {{"verdict": "pass"}}
  Some tests fail because the app breaks the spec:
  args {{"verdict": "fail", "failures": [{{"test": "<test name>", "rule": "<spec endpoint or rule it checks>",
         "expected": "<what the spec requires>", "got": "<what the app did>"}}]}}

Already written for you (do not repeat these checks): tests/test_contract.py covers missing auth (401),
users on admin endpoints (403), unknown ids (404) and empty bodies (422).

Write tests/test_behaviour.py (more test_*.py files are fine):
- Start with: from fastapi.testclient import TestClient / from app.main import app / client = TestClient(app)
- Only HTTP calls through client. Never import other app modules.
- Auth headers: {{"X-Role": "user" or "admin", "X-User-Id": "<int>"}}. Public endpoints need none.
- Storage is shared by all tests and never reset. Each test creates the records it needs, uses unique values
  (uuid) for unique fields, and never assumes ids, counts or empty lists. Use a different X-User-Id per test
  when ownership matters.
- Dates and datetimes are ISO strings, built relative to now (datetime.now() + timedelta(...)).
- Cover every endpoint's success case (the spec's status_code and the entity's fields plus "id"),
  and every business rule both ways (allowed and refused, with the status code the rule implies:
  409 for conflicts and uniqueness, 422 for invalid values, 404 for records the caller may not see).
- Put r.text in assert messages so failures explain themselves.
- Behaviour the spec does not state is not tested.

When tests fail, judge each one. If the test assumed something the spec does not say, fix the test.
If the app breaks the spec, keep the test and report it. Never weaken a test to hide a real bug.
Work efficiently: write the file, run_tests, fix your own mistakes, run_tests again, then finish."""


# ---------- layer 1: contract tests from the spec (no LLM) ----------

def _headers(access: str) -> dict:
    return {"public": {}, "user": {"X-Role": "user", "X-User-Id": "1"}, "admin": {"X-Role": "admin", "X-User-Id": "1"}}[access]


def contract_tests(spec: Spec) -> str:
    """pytest file checking the conventions every generated API must follow."""
    fill = lambda p, v: re.sub(r"\{[^}]+\}", str(v), p)
    one_param = lambda p: p.count("{") == 1 and p.endswith("}")
    fields = {e.name: {f.name: f for f in e.fields} for e in spec.entities}
    needs_auth, admin_only, unknown, empty_body = [], [], [], []
    for e in spec.endpoints:
        if e.access != "public":
            needs_auth.append((e.method, fill(e.path, 1)))
        if e.access == "admin":
            admin_only.append((e.method, fill(e.path, 1)))
        if e.method in ("GET", "DELETE") and one_param(e.path):
            unknown.append((e.method, fill(e.path, 999999), _headers(e.access)))
        required = [n for n in e.request_fields if (f := fields.get(e.entity, {}).get(n)) and f.required]
        if e.method in ("POST", "PUT") and required:
            empty_body.append((e.method, fill(e.path, 1), _headers(e.access)))
    head = '''"""Contract tests generated from spec.json (no LLM): auth, unknown ids and invalid bodies."""
import pytest
from fastapi.testclient import TestClient

from app.main import app

client = TestClient(app)
'''
    checks = [
        (needs_auth, '''
@pytest.mark.parametrize("method,path", {cases!r})
def test_requires_auth(method, path):
    r = client.request(method, path)
    assert r.status_code == 401, f"{{method}} {{path}} without X-Role: {{r.status_code}} {{r.text}}"
'''),
        (admin_only, '''
@pytest.mark.parametrize("method,path", {cases!r})
def test_user_cannot_call_admin_endpoint(method, path):
    r = client.request(method, path, headers={{"X-Role": "user", "X-User-Id": "1"}})
    assert r.status_code == 403, f"{{method}} {{path}} as user: {{r.status_code}} {{r.text}}"
'''),
        (unknown, '''
@pytest.mark.parametrize("method,path,headers", {cases!r})
def test_unknown_id_is_404(method, path, headers):
    r = client.request(method, path, headers=headers)
    assert r.status_code == 404, f"{{method}} {{path}}: {{r.status_code}} {{r.text}}"
'''),
        (empty_body, '''
@pytest.mark.parametrize("method,path,headers", {cases!r})
def test_empty_body_is_422(method, path, headers):
    r = client.request(method, path, json={{}}, headers=headers)
    assert r.status_code == 422, f"{{method}} {{path}} with {{{{}}}}: {{r.status_code}} {{r.text}}"
'''),
    ]
    # a check with no cases would show up as a confusing "skipped" in pytest's summary
    return head + "".join("\n" + body.format(cases=cases) for cases, body in checks if cases)


# ---------- layer 2: LLM-written behaviour tests ----------

def _pytest_text(report: dict) -> str:
    if report.get("import_error"):
        return "The app failed to import:\n" + report["import_error"]
    if report.get("error"):
        return "Sandbox error: " + report["error"]
    py = report.get("pytest") or {}
    return py.get("output") or "(no test output)"


def summary_line(report: dict) -> str:
    """Last pytest line, e.g. '31 passed in 0.8s' or '2 failed, 29 passed in 1.1s'."""
    lines = [l.strip("= ") for l in _pytest_text(report).splitlines() if re.search(r"\d+ (passed|failed|error)", l)]
    return lines[-1] if lines else "tests did not run"


def parse_results(report: dict) -> list[dict]:
    """Per-test outcomes from pytest's -rA summary lines, e.g. 'PASSED tests/test_x.py::test_y[a-b]'."""
    out = []
    for m in re.finditer(r"^(PASSED|FAILED|ERROR|SKIPPED|XFAIL|XPASS) (tests/[^:\s]+)::(\S+)", _pytest_text(report), re.M):
        out.append({"file": m.group(2), "name": m.group(3), "outcome": m.group(1).lower()})
    return out


def make_tools(ws: pathlib.Path, status: dict) -> list[Tool]:
    def safe_test(path: str) -> pathlib.Path:
        p = (ws / path).resolve()
        rel = p.relative_to(ws) if ws in p.parents else None
        if rel is None or rel.parts[0] != "tests" or not p.name.startswith("test_") or p.suffix != ".py":
            raise ValueError("tests must be tests/test_*.py files")
        return p

    def write_test(path: str, content: str) -> str:
        p = safe_test(path)
        if str(p.relative_to(ws)) == CONTRACT_FILE:
            raise ValueError("test_contract.py is generated; write your tests in another file")
        if len(content) > MAX_FILE:
            raise ValueError(f"file too large ({len(content)} chars, max {MAX_FILE})")
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(content)
        status["fresh"] = False
        return f"wrote {p.relative_to(ws)} ({len(content)} chars)"

    def read_test(path: str) -> str:
        return safe_test(path).read_text()

    def run_tests() -> str:
        report = run_checks(str(ws))
        py = report.get("pytest") or {}
        status.update(fresh=True, passed=bool(py.get("passed")) and not report.get("import_error"), report=report)
        return ("ALL TESTS PASSED\n" if status["passed"] else "SOME TESTS FAILED\n") + _pytest_text(report)

    return [
        Tool("write_test", "Create or overwrite a tests/test_*.py file with the full content.",
             {"type": "object", "properties": {"path": {"type": "string"}, "content": {"type": "string"}},
              "required": ["path", "content"]}, write_test),
        Tool("read_test", "Read one of the test files.",
             {"type": "object", "properties": {"path": {"type": "string"}}, "required": ["path"]}, read_test),
        Tool("run_tests", "Run every test in tests/ against the app in the sandbox. Returns pytest's output.",
             {"type": "object", "properties": {}}, run_tests),
    ]


def format_report(failures: list[dict], summary: str) -> str:
    """The failure-report format the coder receives (agreed with Role 3)."""
    lines = [f"Tester report: {summary}. The tests are in tests/ and run inside run_checks.",
             "Fix the app so they pass. You cannot change the tests."]
    for f in failures:
        lines.append(f"- {f.get('test', '?')}: {f.get('rule', '')}\n  expected: {f.get('expected', '')}\n  got: {f.get('got', '')}")
    return "\n".join(lines)


def _trim(step: dict) -> str:
    args = step.get("args") or {}
    if isinstance(args, dict) and isinstance(args.get("content"), str) and len(args["content"]) > 300:
        args = {**args, "content": f"<{len(args['content'])} chars, written to disk>"}
    return json.dumps({**step, "args": args})


def _finish(args: dict, status: dict) -> Optional[str]:
    """None if finish is allowed, else the reason it's refused."""
    if not status["fresh"]:
        return "Cannot finish: run_tests has not run since your last change."
    verdict = args.get("verdict")
    if verdict == "pass":
        return None if status["passed"] else "Cannot finish with pass: tests failed. Fix your tests or report the failures."
    if verdict == "fail":
        if status["passed"]:
            return "Cannot finish with fail: all tests passed. Use verdict pass."
        if not isinstance(args.get("failures"), list) or not args["failures"]:
            return "Cannot finish with fail: list each failing test in failures."
        return None
    return 'Cannot finish: verdict must be "pass" or "fail".'


def run(state: ProjectState, llm: LLM, on_step: Optional[Callable[[LogEntry], None]] = None) -> ProjectState:
    if not state.build_ok or not state.workspace:
        raise ValueError("tester needs a built workspace")
    ws = pathlib.Path(state.workspace).resolve()
    (ws / "tests").mkdir(exist_ok=True)
    (ws / CONTRACT_FILE).write_text(contract_tests(state.spec))

    def log(action, detail="", tokens=0, seconds=0.0):
        state.logs.append(LogEntry(agent="tester", action=action, detail=detail[:300], tokens=tokens, seconds=seconds))
        if on_step:
            on_step(state.logs[-1])

    log("contract", f"Generated contract tests for {len(state.spec.endpoints)} endpoints")
    status = {"fresh": False, "passed": False, "report": None}
    tools = {t.name: t for t in make_tools(ws, status)}
    system = SYSTEM.format(tools=describe(list(tools.values())))
    msgs = [{"role": "user", "content": f"API spec:\n{state.spec.model_dump_json(indent=1)}"}]

    for step_no in range(1, MAX_STEPS + 1):
        t0, tok0 = time.time(), llm.tokens
        try:
            reply = llm(system, msgs)
        except Exception as e:  # provider failure: keep whatever tests exist, judge by running them
            log("gave_up", f"LLM error at step {step_no}: {type(e).__name__}: {str(e)[:200]}")
            return recheck(state, on_step)
        try:
            step = extract_json(reply)
            action, args = step["action"], step.get("args") or {}
            if not isinstance(args, dict):
                raise ValueError("args must be an object")
        except (ValueError, KeyError, TypeError) as e:
            step, action, args = {"thought": f"invalid reply: {e}"}, "invalid", {}
            obs = f"Invalid reply ({e}). Reply with ONE JSON object: thought, action, args."
        else:
            if action == "finish":
                obs = _finish(args, status)
            elif action in tools:
                try:
                    obs = tools[action].fn(**args)
                except Exception as e:
                    obs = f"Tool error: {type(e).__name__}: {e}"
            else:
                obs = f"Unknown action {action!r}. Use one of: {', '.join(tools)}, finish."
        log(action, str(step.get("thought", "")), llm.tokens - tok0, round(time.time() - t0, 3))

        if action == "finish" and obs is None:
            summary = summary_line(status["report"])
            state.test_summary = summary
            state.test_results = parse_results(status["report"])
            state.tests_ok = args["verdict"] == "pass"
            state.test_report = None if state.tests_ok else format_report(args["failures"], summary)
            log("verdict", summary if state.tests_ok else f"{len(args['failures'])} bugs found: {summary}")
            return state
        msgs += [{"role": "assistant", "content": _trim(step)},
                 {"role": "user", "content": f"Observation:\n{str(obs)[-MAX_OBS:]}"}]

    log("gave_up", f"{MAX_STEPS} steps without a verdict")
    return recheck(state, on_step)


def recheck(state: ProjectState, on_step: Optional[Callable[[LogEntry], None]] = None) -> ProjectState:
    """Run the existing suite without the LLM (after a coder fix round, or when the tester gave up)."""
    report = run_checks(state.workspace)
    py = report.get("pytest") or {}
    state.tests_ok = bool(py.get("passed")) and not report.get("import_error")
    state.test_summary = summary_line(report)
    state.test_results = parse_results(report)
    if state.tests_ok:
        state.test_report = None
    elif not state.test_report:  # no LLM triage available: pass pytest's own output on
        state.test_report = "Tester report: " + state.test_summary + "\n" + _pytest_text(report)[-3000:]
    state.logs.append(LogEntry(agent="tester", action="verdict", detail=state.test_summary))
    if on_step:
        on_step(state.logs[-1])
    return state
