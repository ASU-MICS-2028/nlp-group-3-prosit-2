"""Deterministic project files around the generated code, and zip export.

The coder LLM writes app/. This module writes everything a developer expects next to it
(README, requirements, Dockerfile, ignores) from the spec, so they are always correct.
"""
import io
import pathlib
import zipfile

from core.spec import Spec

SKIP = {"__pycache__", ".pytest_cache", "state.json"}  # internal / generated junk, never exported

REQUIREMENTS = "fastapi>=0.110\nuvicorn[standard]>=0.29\npydantic>=2.6\n"

DOCKERFILE = """FROM python:3.12-slim
WORKDIR /srv
COPY requirements.txt .
RUN pip install --no-cache-dir -r requirements.txt
COPY app ./app
RUN useradd --create-home api
USER api
EXPOSE 8000
CMD ["uvicorn", "app.main:app", "--host", "0.0.0.0", "--port", "8000"]
"""

GITIGNORE = "__pycache__/\n*.pyc\n.venv/\n.env\n.pytest_cache/\n"
DOCKERIGNORE = GITIGNORE + "tests/\n.git/\n"


def _tree(ws: pathlib.Path) -> str:
    lines = []
    for p in sorted(ws.rglob("*")):
        rel = p.relative_to(ws)
        if SKIP & set(rel.parts) or p.name == "__init__.py":
            continue
        lines.append("    " * (len(rel.parts) - 1) + (f"{p.name}/" if p.is_dir() else p.name))
    return "\n".join(lines)


def _readme(ws: pathlib.Path, spec: Spec) -> str:
    slug = ws.name
    endpoints = "\n".join(f"| `{e.method}` | `{e.path}` | {e.access} | {e.summary} |" for e in spec.endpoints)
    entities = "\n".join(
        f"- **{e.name}**: " + ", ".join(f"`{f.name}` ({f.type}{', read-only' if f.read_only else ''}"
                                        f"{', optional' if not f.required else ''})" for f in e.fields)
        for e in spec.entities)
    rules = "\n".join(f"- {r}" for r in spec.rules) or "- None"
    tests = """
## Tests

```bash
pip install pytest httpx
python -m pytest
```

`tests/test_contract.py` checks auth, unknown ids and invalid input for every endpoint.
`tests/test_behaviour.py` checks each endpoint and business rule against the spec.
""" if (ws / "tests").is_dir() else ""
    return f"""# {spec.project_name}

{spec.description}

## Run locally

```bash
python -m venv .venv && source .venv/bin/activate
pip install -r requirements.txt
uvicorn app.main:app --reload
```

Interactive docs: http://127.0.0.1:8000/docs

## Run with Docker

```bash
docker build -t {slug} .
docker run --rm -p 8000:8000 {slug}
```

{tests}
## Authentication

Requests identify the caller with two headers:

| Header | Values | Meaning |
| --- | --- | --- |
| `X-Role` | `user`, `admin` | Missing on a protected endpoint gives 401; `user` on an admin endpoint gives 403. |
| `X-User-Id` | integer | Owner of the records the caller creates and can see. |

Endpoints marked `public` need no headers.

## Endpoints

| Method | Path | Access | Description |
| --- | --- | --- | --- |
{endpoints}

## Data model

{entities}

## Business rules

{rules}

## Project structure

```
{_tree(ws)}
```

Data is kept in memory and resets when the server restarts. `spec.json` is the API spec the code was built from.

_Generated by Prosit Builder._
"""


def scaffold(ws: pathlib.Path, spec: Spec) -> None:
    (ws / "requirements.txt").write_text(REQUIREMENTS)
    (ws / "Dockerfile").write_text(DOCKERFILE)
    (ws / ".gitignore").write_text(GITIGNORE)
    (ws / ".dockerignore").write_text(DOCKERIGNORE)
    (ws / "README.md").write_text(_readme(ws, spec))  # last, so the structure tree includes the files above


def export_zip(ws: pathlib.Path) -> bytes:
    """Zip the project under a top-level folder named after it, without internal files."""
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for p in sorted(ws.rglob("*")):
            rel = p.relative_to(ws)
            if p.is_file() and not (SKIP & set(rel.parts)):
                z.write(p, f"{ws.name}/{rel}")
    return buf.getvalue()
